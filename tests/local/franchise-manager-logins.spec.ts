import { test, expect } from "@playwright/test";
const path = "/dashboard/franchise/stores/management-fixture";
test("login history is the default, paginates and filters real record fields, and refreshes", async ({page}) => {
  await page.goto(path);
  await expect(page.getByRole("tab")).toHaveText(["Manager Login History", "Staff Management", "Store Settings"]);
  await expect(page.getByRole("tab",{name:"Manager Login History",exact:true})).toHaveAttribute("aria-selected","true");
  const panel=page.getByRole("tabpanel");
  await expect(panel.getByRole("button",{name:"Assign Manager",exact:true})).toHaveCount(0);
  await expect(panel.getByRole("columnheader")).toHaveText(["Manager","Date & Time","IP Address","Device / Browser","Status"]);
  const rows=panel.locator("tbody tr");
  await expect(rows).toHaveCount(25);
  await expect(rows.first()).toContainText("Manager 1");
  await expect(rows.first()).toContainText("14:00:00");
  await expect(rows.nth(1)).toContainText("Not recorded");
  await panel.getByRole("button",{name:"Next",exact:true}).click();
  await expect(rows).toHaveCount(3);
  await expect(panel.getByRole("status")).toContainText("Page 2");
  await panel.getByRole("combobox",{name:"Manager",exact:true}).selectOption("10000000-0000-4000-8000-000000000002");
  await panel.getByRole("button",{name:"Apply filters"}).click();
  await expect(rows).toHaveCount(14);
  await expect(panel.getByRole("status")).toContainText("Page 1");
  for (const row of await rows.all()) await expect(row.getByRole("cell").first()).toHaveText("Manager 2");
  await panel.getByLabel("From",{exact:true}).fill("2026-10-15");
  await panel.getByLabel("To",{exact:true}).fill("2026-10-15");
  await panel.getByRole("combobox",{name:"Login status",exact:true}).selectOption("success");
  await panel.getByRole("button",{name:"Apply filters"}).click();
  await expect(rows).toHaveCount(7);
  await panel.getByRole("button",{name:"Refresh history"}).click();
  await expect(panel.getByRole("status")).toContainText("Page 1");
  await page.route("**/fixture-manager-history",route=>route.fulfill({status:503,body:"Unavailable"}));
  await panel.getByRole("button",{name:"Refresh history"}).click();
  await expect(panel.getByRole("alert")).toContainText("could not be loaded");
  await expect(rows).toHaveCount(7);
});
test("staff management retains assignment limits, account actions and settings", async ({page}) => {
  await page.goto(path);
  await page.getByRole("tab",{name:"Staff Management",exact:true}).click();
  const panel=page.getByRole("tabpanel");
  await expect(panel.getByRole("button",{name:"Assign Manager",exact:true})).toBeDisabled();
  await expect(panel.getByRole("button",{name:"Add Receptionist (5/5)",exact:true})).toBeDisabled();
  await panel.getByRole("button",{name:"Manage",exact:true}).first().click();
  await expect(panel.getByRole("combobox",{name:"Action",exact:true}).locator("option")).toHaveText(["Edit details","Restrict access","Reactivate access","Deactivate account","Send password reset","Remove manager assignment"]);
  await page.getByRole("tab",{name:"Manager Login History",exact:true}).click();
  await expect(panel.getByRole("button",{name:"Confirm action",exact:true})).toHaveCount(0);
  await page.getByRole("tab",{name:"Store Settings",exact:true}).click();
  await expect(panel.getByRole("heading",{name:"Store Settings",exact:true})).toBeVisible();
  await expect(page.getByRole("heading",{name:"Alpha Store",exact:true})).toBeVisible();
  await page.goto(path+"?slots");
  await page.getByRole("tab",{name:"Staff Management",exact:true}).click();
  await panel.getByRole("button",{name:"Assign Manager",exact:true}).click();
  await expect(panel.getByRole("heading",{name:"Assign Manager",exact:true})).toBeVisible();
  await expect(panel.locator('input[name="role"]')).toHaveValue("manager");
  const managerForm=panel.locator("form").filter({has:page.getByRole("heading",{name:"Assign Manager",exact:true})});
  await expect(managerForm.locator('input:not([type="hidden"])')).toHaveCount(2);
  await expect(managerForm.getByLabel("Manager Email Address",{exact:true})).toBeVisible();
  await expect(managerForm.getByLabel("Temporary Password",{exact:true})).toHaveAttribute("type","password");
  await expect(managerForm.locator('input[name="actorPassword"],input[name="confirmPassword"],input[name="firstName"],input[name="surname"],input[name="phone"]')).toHaveCount(0);
  await panel.getByRole("button",{name:"Add Receptionist (4/5)",exact:true}).click();
  await expect(panel.getByRole("heading",{name:"Add Receptionist",exact:true})).toBeVisible();
  await expect(panel.locator('input[name="role"]')).toHaveValue("receptionist");
  const receptionistForm=panel.locator("form").filter({has:page.getByRole("heading",{name:"Add Receptionist",exact:true})});
  await expect(receptionistForm.locator('input:not([type="hidden"])')).toHaveCount(2);
  await receptionistForm.getByLabel("Receptionist Email Address",{exact:true}).fill("employee@example.test");
  await receptionistForm.getByLabel("Temporary Password",{exact:true}).fill("abcdefgh");
  expect(await receptionistForm.evaluate(form=>(form as HTMLFormElement).checkValidity())).toBe(true);
  await expect(receptionistForm.getByText(/uppercase|symbol|number/, {exact:false})).toHaveCount(0);
});
test("login table stays readable across screen sizes with compact empty state", async ({page}) => {
  await page.goto(path);
  for (const width of [1440,768,390,320]) {
    await page.setViewportSize({width,height:1000});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    const table=page.getByRole("region",{name:"Manager login records",exact:true});
    await expect(table).toBeVisible();
    if(width<768) expect(await table.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true);
    if(width===1440||width===390) await page.screenshot({path:`tmp/manager-logins-${width}.png`,fullPage:true});
  }
  await page.goto(path+"?empty");
  await expect(page.getByRole("cell",{name:"No manager login activity recorded for this store.",exact:true})).toBeVisible();
  expect(await page.getByRole("region",{name:"Manager login records",exact:true}).evaluate(el=>el.getBoundingClientRect().height)).toBeLessThan(180);
});
